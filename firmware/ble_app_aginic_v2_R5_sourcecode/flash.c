typedef union flash_records_page_t
{
	uint16_t		data[FLASH_PAGE_SIZE/2];
	reid_ble_summary_packet_t	records[FLASH_PAGE_RECORDS];
} flash_records_page_t;

const __attribute__((used)) uint8_t copyright_message[] /*__attribute__((used))*/ = "   Written by Alex Gilmour. Copyright (c) 2022 Reid Technologies. All rights reserved.   ";

const volatile __attribute__((aligned(FLASH_PAGE_SIZE),used)) flash_records_page_t flash_measurements[FLASH_NUM_PAGES] = \
{BLANK_PAGE,BLANK_PAGE,BLANK_PAGE,BLANK_PAGE,BLANK_PAGE,\
BLANK_PAGE,BLANK_PAGE,BLANK_PAGE,BLANK_PAGE,BLANK_PAGE};

static volatile uint32_t flash_high_index;

static void flash_erase_generic(uint16_t* flash);	// erases a single segment of flash
static void flash_write_generic(uint16_t* flash, const uint16_t* data, uint16_t length_bytes);
static void flash_write_16bit(uint32_t flash, uint16_t data);

static inline void wait_for_flash_ready(void)
{
    while (NRF_NVMC->READY == NVMC_READY_READY_Busy) {;}
}

void flash_init(void)
{
	flash_sysdata.device_uid = NRF_FICR->DEVICEADDR[0];
	flash_sysdata.device_version = DEVICE_FW_VERSION;
	
	uint32_t max_time_s = 0;
	max_time_s = (*((volatile uint8_t*)copyright_message))-0x20;
	
    flash_high_index = 0;
	// initialise the counters
	for (uint32_t i=0; i<FLASH_NUM_PAGES; ++i) {
		for (uint32_t j=0; j<FLASH_PAGE_RECORDS; ++j) {
			if   (((*((volatile uint32_t*)&flash_measurements[i].records[j].time_s_start)) != 0xFFFFFFFF)
				&&((*((volatile uint32_t*)&flash_measurements[i].records[j].time_s_end)) != 0xFFFFFFFF)
				&&((*((volatile uint32_t*)&flash_measurements[i].records[j].index)) != 0xFFFFFFFF)
				&&((*((volatile uint32_t*)&flash_measurements[i].records[j].index)) >= flash_high_index))
			{
				flash_high_index = (*((volatile uint32_t*)&flash_measurements[i].records[j].index))+1;
				max_time_s = (*((volatile uint32_t*)&flash_measurements[i].records[j].time_s_end));
			}
		}
	}
	//write_index %= (FLASH_PAGE_RECORDS * FLASH_NUM_PAGES);
	system_set_time(max_time_s+5);
	// check for empty spot; if it's not empty and we're on the edge of a page, advance to the next page
    reid_ble_summary_packet_t* next_write = (reid_ble_summary_packet_t*) &flash_measurements[(flash_high_index/FLASH_PAGE_RECORDS)%FLASH_NUM_PAGES].records[flash_high_index%FLASH_PAGE_RECORDS];
	if (((next_write->time_s_start) != 0xFFFFFFFF)||((next_write->time_s_end) != 0xFFFFFFFF)||((next_write->index) != 0xFFFFFFFF)) {
		flash_high_index = (((flash_high_index-1)/FLASH_PAGE_RECORDS)+1)*FLASH_PAGE_RECORDS;
	}
	// the write procedure will automatically erase on a new page anyway
	return;
}

void flash_deinit(void)
{
	return;
}

void flash_reset_all(void)
{
	ble_reid_force_disconnect();

	for (uint32_t i=0; i < FLASH_NUM_PAGES; ++i)
	{
		flash_erase_generic((uint16_t*) &(flash_measurements[i].records[0]));
	}
	flash_high_index = (((flash_high_index-1)/FLASH_PAGE_RECORDS)+1)*FLASH_PAGE_RECORDS;
	
    ble_advertise_again();
}

void flash_write_record(reid_ble_summary_packet_t* record)
{
	ble_reid_force_disconnect();

	static volatile reid_ble_summary_packet_t data_to_copy;
	memcpy((reid_ble_summary_packet_t*)&data_to_copy, record, sizeof(reid_ble_summary_packet_t));
    data_to_copy.index = flash_high_index;

	uint16_t* write_to = (uint16_t*) &(flash_measurements[(flash_high_index/FLASH_PAGE_RECORDS)%FLASH_NUM_PAGES].records[(flash_high_index%FLASH_PAGE_RECORDS)]);
	
	if ((flash_high_index % FLASH_PAGE_RECORDS) == 0) flash_erase_generic((uint16_t*) &(flash_measurements[(flash_high_index/FLASH_PAGE_RECORDS)% FLASH_NUM_PAGES].records[0]));

	flash_write_generic(write_to, (uint16_t*) &data_to_copy, sizeof(reid_ble_summary_packet_t));
	++flash_high_index;
	
    ble_advertise_again();
}

reid_ble_summary_packet_t* flash_get_record(uint32_t req_index)
{
	reid_ble_summary_packet_t* ret_val = (reid_ble_summary_packet_t*) &flash_measurements[(req_index/FLASH_PAGE_RECORDS)%FLASH_NUM_PAGES].records[req_index%FLASH_PAGE_RECORDS];
	if (((ret_val->time_s_start) != 0xFFFFFFFF)&&((ret_val->time_s_end) != 0xFFFFFFFF)&&(ret_val->index == req_index)) {
		return ret_val;
	} else {
		return NULL;
	}
}

void flash_get_all_indices(uint32_t* low_index, uint32_t* high_index)
{
	uint32_t ret_high = 0;
	uint32_t ret_low = 0xFFFFFFFFul;

	for (uint32_t i=0; i<FLASH_NUM_PAGES; ++i)
	{
		for (uint32_t j=0; j<FLASH_PAGE_RECORDS; ++j)
		{
			if (((*((volatile uint32_t*)&flash_measurements[i].records[j].time_s_start)) != 0xFFFFFFFF)
			 && ((*((volatile uint32_t*)&flash_measurements[i].records[j].time_s_end)) != 0xFFFFFFFF))
			{
				if ((*((volatile uint32_t*)&flash_measurements[i].records[j].index)) > ret_high) ret_high = (*((volatile uint32_t*)&flash_measurements[i].records[j].index));
				if ((*((volatile uint32_t*)&flash_measurements[i].records[j].index)) < ret_low) ret_low = (*((volatile uint32_t*)&flash_measurements[i].records[j].index));
			}
		}
	}

	if (low_index != NULL) *low_index = ret_low;
	if (high_index != NULL) *high_index = ret_high;
}

